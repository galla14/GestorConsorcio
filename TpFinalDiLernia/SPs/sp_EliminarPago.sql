CREATE PROCEDURE sp_EliminarPago
	@Id_Pago UNIQUEIDENTIFIER
AS
BEGIN
	BEGIN TRY
		IF NOT EXISTS(SELECT * FROM dbo.Pago WHERE IdPago = @Id_Pago)
			BEGIN
				RETURN -1;
			END

		DELETE dbo.Pago
		WHERE IdPago = @Id_Pago
	END TRY
	BEGIN CATCH
		THROW;
	END CATCH
END
GO
