CREATE PROCEDURE sp_EliminarUsuario
	@Id_Usuario UNIQUEIDENTIFIER
AS
BEGIN
	SET NOCOUNT ON;
	BEGIN TRY
		IF NOT EXISTS(SELECT * FROM dbo.Usuario WHERE IdUsuario = @Id_Usuario)
			BEGIN
				RETURN -1;
			END
		DELETE dbo.Usuario
		WHERE IdUsuario = @Id_Usuario

		RETURN 1;
	END TRY
	BEGIN CATCH
		THROW;
	END CATCH
END
GO
